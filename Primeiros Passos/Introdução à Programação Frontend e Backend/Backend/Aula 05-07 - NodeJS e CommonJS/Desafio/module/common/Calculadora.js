exports.somar = function (valorX, valorY) {
    return valorX + valorY;
}

exports.subtrair = function (valorX, valorY) {
    return valorX - valorY;
}

exports.multiplicar = function (valorX, valorY) {
    return valorX * valorY;
}

exports.dividir = function (valorX, valorY) {
    return valorX / valorY;
}


